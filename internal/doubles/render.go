package doubles

import (
	"fmt"
	"strings"

	"github.com/cafecito-games/gdparser"
	"github.com/cafecito-games/gdparser/format"
)

// Render returns the formatted GDScript source of the double described by model.
// productVersion is written into the header, so it must name the gdtest build
// that generates the file. The output has no absolute paths and no timestamps.
// It returns an error only when the model is incomplete or the text fails to
// parse, which means the renderer itself is wrong.
func Render(model Model, productVersion string) ([]byte, error) {
	for _, method := range model.Methods {
		if method.ReturnCheck == ReturnCheckUnsupported {
			return nil, fmt.Errorf("render double %s: method %s has no return check", model.OutputResource, method.Name)
		}
	}
	var builder strings.Builder
	writeHeader(&builder, model, productVersion)
	writeDoubleDeclaration(&builder, model)
	writeConstructor(&builder, model)
	for _, method := range model.Methods {
		writeMethod(&builder, model, method)
	}
	writeControls(&builder, model)
	for _, method := range model.Methods {
		writeController(&builder, method)
	}
	tree, err := gdparser.ParseFile(model.OutputResource, []byte(builder.String()))
	if err != nil {
		return nil, fmt.Errorf("parse rendered double %s: %w", model.OutputResource, err)
	}
	return []byte(format.FileWithOptions(tree, format.GodotStyle())), nil
}

// ownershipMarkerPrefix is the first line of every generated double, before the
// source resource. Its exact form is matched by ownershipMarker.
const ownershipMarkerPrefix = "# gdtest:generated-double v1 source="

func writeHeader(builder *strings.Builder, model Model, productVersion string) {
	builder.WriteString(ownershipMarkerPrefix + model.SourceResource + "\n")
	builder.WriteString("# Generated by gdtest " + productVersion + ". Do not edit; run `gdtest generate doubles`.\n")
}

func writeDoubleDeclaration(builder *strings.Builder, model Model) {
	builder.WriteString("## Test double for " + model.SourceResource + ".\n")
	if model.ClassName != "" {
		builder.WriteString("class_name " + model.ClassName + "\n")
	}
	builder.WriteString("extends " + gdscriptString(model.SourceResource) + "\n")
	builder.WriteString("\n")
	builder.WriteString("## Path of this generated script, used to locate callers in failure reports.\n")
	builder.WriteString("const _GDTEST_DOUBLE_PATH: String = " + gdscriptString(model.OutputResource) + "\n")
	builder.WriteString("\n")
	builder.WriteString("## Typed stubbing controls for every doubled method.\n")
	builder.WriteString("var gdtest: GDTestControls\n")
}

func writeConstructor(builder *strings.Builder, model Model) {
	separateDeclarations(builder)
	parameters := []string{"context: GDTestDoubleContext"}
	for _, parameter := range model.Constructor.Parameters {
		parameters = append(parameters, parameterDeclaration(parameter))
	}
	if model.Constructor.HasInit {
		builder.WriteString("## Creates a double bound to `context`; remaining arguments reach the real constructor.\n")
	} else {
		builder.WriteString("## Creates a double bound to `context`.\n")
	}
	builder.WriteString("func _init(" + strings.Join(parameters, ", ") + ") -> void:\n")
	builder.WriteString("\tgdtest = GDTestControls.new(context)\n")
	if model.Constructor.HasInit {
		builder.WriteString("\tsuper(" + argumentNames(model.Constructor.Parameters) + ")\n")
	}
}

func writeMethod(builder *strings.Builder, model Model, method Method) {
	separateDeclarations(builder)
	builder.WriteString("## Records the call and returns the configured result.\n")
	builder.WriteString("func " + method.Name + "(" + parameterList(method.Parameters) + ") -> " + method.ReturnType + ":\n")
	builder.WriteString("\tvar gdtest_method: " + method.ControllerName + " = gdtest." + method.Name + "\n")
	builder.WriteString("\tvar gdtest_outcome: int = gdtest_method._gdtest_next(" + argumentArray(method.Parameters) + ")\n")
	if method.ReturnCheck == ReturnCheckVoid {
		writeVoidBody(builder, method)
		return
	}
	writeValueBody(builder, method)
}

// writeVoidBody emits the branches of a method without a return value.
func writeVoidBody(builder *strings.Builder, method Method) {
	realCall := awaitPrefix(method) + "super." + method.Name + "(" + argumentNames(method.Parameters) + ")"
	answerCall := awaitPrefix(method) + "gdtest_method._gdtest_answer().call(" + argumentNames(method.Parameters) + ")"
	if method.Abstract {
		builder.WriteString("\tif gdtest_outcome == GDTestDoubleMethod.OUTCOME_ANSWER:\n")
		builder.WriteString("\t\t" + answerCall + "\n")
		return
	}
	builder.WriteString("\tif gdtest_outcome == GDTestDoubleMethod.OUTCOME_REAL:\n")
	builder.WriteString("\t\t" + realCall + "\n")
	builder.WriteString("\telif gdtest_outcome == GDTestDoubleMethod.OUTCOME_ANSWER:\n")
	builder.WriteString("\t\t" + answerCall + "\n")
}

// writeValueBody emits the branches of a method with a return value, checking
// the configured answer against the declared return type.
func writeValueBody(builder *strings.Builder, method Method) {
	if !method.Abstract {
		builder.WriteString("\tif gdtest_outcome == GDTestDoubleMethod.OUTCOME_REAL:\n")
		builder.WriteString("\t\treturn " + awaitPrefix(method) + "super." + method.Name + "(" + argumentNames(method.Parameters) + ")\n")
	}
	builder.WriteString("\tvar gdtest_value: Variant = gdtest_method._gdtest_value()\n")
	builder.WriteString("\tif gdtest_outcome == GDTestDoubleMethod.OUTCOME_ANSWER:\n")
	builder.WriteString("\t\tgdtest_value = " + awaitPrefix(method) + "gdtest_method._gdtest_answer().call(" + argumentNames(method.Parameters) + ")\n")
	builder.WriteString("\tvar gdtest_result: " + method.ReturnType + "\n")
	builder.WriteString("\tif gdtest_outcome != GDTestDoubleMethod.OUTCOME_NEUTRAL:\n")
	if method.ReturnCheck == ReturnCheckAny {
		builder.WriteString("\t\tgdtest_result = gdtest_value\n")
	} else {
		builder.WriteString("\t\tif " + returnCondition(method) + ":\n")
		builder.WriteString("\t\t\tgdtest_result = gdtest_value\n")
		builder.WriteString("\t\telse:\n")
		builder.WriteString("\t\t\tgdtest_method._gdtest_reject_return(gdtest_value, " + gdscriptString(method.ExpectedType) + ")\n")
	}
	builder.WriteString("\treturn gdtest_result\n")
}

// returnCondition is the check that a configured answer must pass for a method
// with a typed return. It is empty for void and Variant returns.
func returnCondition(method Method) string {
	switch method.ReturnCheck {
	case ReturnCheckBuiltin:
		return "gdtest_value is " + method.ReturnType
	case ReturnCheckTypedArray:
		return "gdtest_value is Array and gdtest_result.is_same_typed(gdtest_value)"
	case ReturnCheckTypedDictionary:
		return "gdtest_value is Dictionary and gdtest_result.is_same_typed(gdtest_value)"
	case ReturnCheckEnum:
		return "gdtest_value is int"
	case ReturnCheckObject:
		return "gdtest_value == null or gdtest_value is " + method.ReturnType
	}
	return ""
}

func writeControls(builder *strings.Builder, model Model) {
	separateDeclarations(builder)
	builder.WriteString("## Typed controllers for every doubled method of " + model.SourceResource + ".\n")
	builder.WriteString("class GDTestControls extends RefCounted:\n")
	for _, method := range model.Methods {
		builder.WriteString("\t## Controls calls to `" + method.Name + "`.\n")
		builder.WriteString("\tvar " + method.Name + ": " + method.ControllerName + "\n")
	}
	builder.WriteString("\n")
	builder.WriteString("\t## Creates controllers that report through `context`.\n")
	builder.WriteString("\tfunc _init(context: GDTestDoubleContext) -> void:\n")
	if len(model.Methods) == 0 {
		builder.WriteString("\t\tpass\n")
	}
	for _, method := range model.Methods {
		fmt.Fprintf(builder, "\t\t%s = %s.new(context, %s, _GDTEST_DOUBLE_PATH, %d, %t)\n",
			method.Name, method.ControllerName, gdscriptString(displayName(model, method)),
			len(method.Parameters), method.Abstract)
	}
}

func writeController(builder *strings.Builder, method Method) {
	separateDeclarations(builder)
	builder.WriteString("## Typed controller for `" + method.Name + "`.\n")
	builder.WriteString("class " + method.ControllerName + " extends GDTestDoubleMethod:\n")
	if method.ReturnCheck == ReturnCheckVoid {
		builder.WriteString("\t## Marks the next call to `" + method.Name + "` as expected.\n")
		builder.WriteString("\tfunc then_return() -> void:\n")
		builder.WriteString("\t\t_gdtest_enqueue_value(null)\n")
		return
	}
	builder.WriteString("\t## Queues `value` as the next result of `" + method.Name + "`.\n")
	builder.WriteString("\tfunc then_return(value: " + method.ReturnType + ") -> void:\n")
	builder.WriteString("\t\t_gdtest_enqueue_value(value)\n")
}

// separateDeclarations starts a new top-level declaration after two blank lines,
// the layout that the formatter keeps for functions and classes.
func separateDeclarations(builder *strings.Builder) {
	builder.WriteString("\n\n")
}

// displayName is the name that failure reports use for a doubled method.
func displayName(model Model, method Method) string {
	owner := model.SourceClassName
	if owner == "" {
		owner = model.SourceResource
	}
	return owner + "." + method.Name
}

func awaitPrefix(method Method) string {
	if method.Async {
		return "await "
	}
	return ""
}

func parameterDeclaration(parameter Parameter) string {
	if parameter.Default == "" {
		return parameter.Name + ": " + parameter.Type
	}
	return parameter.Name + ": " + parameter.Type + " = " + parameter.Default
}

func parameterList(parameters []Parameter) string {
	declarations := make([]string, 0, len(parameters))
	for _, parameter := range parameters {
		declarations = append(declarations, parameterDeclaration(parameter))
	}
	return strings.Join(declarations, ", ")
}

func argumentNames(parameters []Parameter) string {
	names := make([]string, 0, len(parameters))
	for _, parameter := range parameters {
		names = append(names, parameter.Name)
	}
	return strings.Join(names, ", ")
}

func argumentArray(parameters []Parameter) string {
	return "[" + argumentNames(parameters) + "]"
}

// gdscriptString quotes value as a GDScript string literal. Only the characters
// that need escaping in a double-quoted literal are escaped, because the values
// are project paths and type names.
func gdscriptString(value string) string {
	escaped := strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(value)
	return `"` + escaped + `"`
}
