func TestRenderVoidMethodHasNoValueBranches(t *testing.T) {
	t.Parallel()

	rendered := renderSource(t, "extends RefCounted\n\nfunc clear() -> void:\n\tpass\n", "")
	assertContainsLines(t, rendered,
		"func clear() -> void:",
		"\tvar gdtest_method: ClearMethod = gdtest.clear",
		"\tvar gdtest_outcome: int = gdtest_method._gdtest_next([])",
		"\tif gdtest_outcome == GDTestDoubleMethod.OUTCOME_REAL:",
		"\t\tsuper.clear()",
		"\telif gdtest_outcome == GDTestDoubleMethod.OUTCOME_ANSWER:",
		"\t\tgdtest_method._gdtest_answer().call()",
	)
	assert.NotContains(t, rendered, "gdtest_value")
	assert.Contains(t, rendered, "func then_return() -> void:\n\t\t_gdtest_enqueue_value(null)\n")
}

