func TestRenderReturnChecksByDeclaredType(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		source  string
		check   []string
		reject  string
		variant bool
	}{
		{
			name:   "builtin",
			source: "extends RefCounted\n\nfunc pick() -> bool:\n\treturn true\n",
			check:  []string{"\t\tif gdtest_value is bool:", "\t\t\tgdtest_result = gdtest_value"},
			reject: `gdtest_method._gdtest_reject_return(gdtest_value, "bool")`,
		},
		{
			name:   "typed array",
			source: "extends RefCounted\n\nfunc pick() -> Array[int]:\n\treturn []\n",
			check:  []string{"\t\tif gdtest_value is Array and gdtest_result.is_same_typed(gdtest_value):"},
			reject: `gdtest_method._gdtest_reject_return(gdtest_value, "Array[int]")`,
		},
		{
			name:   "typed dictionary",
			source: "extends RefCounted\n\nfunc pick() -> Dictionary[String, int]:\n\treturn {}\n",
			check:  []string{"\t\tif gdtest_value is Dictionary and gdtest_result.is_same_typed(gdtest_value):"},
			reject: `gdtest_method._gdtest_reject_return(gdtest_value, "Dictionary[String, int]")`,
		},
		{
			name:   "enum",
			source: "extends RefCounted\n\nenum Mode { FAST, SLOW }\n\nfunc pick() -> Mode:\n\treturn Mode.FAST\n",
			check:  []string{"\t\tif gdtest_value is int:"},
			reject: `gdtest_method._gdtest_reject_return(gdtest_value, "Mode")`,
		},
		{
			name:   "native object",
			source: "extends RefCounted\n\nfunc pick() -> Node:\n\treturn null\n",
			check:  []string{"\t\tif gdtest_value == null or gdtest_value is Node:"},
			reject: `gdtest_method._gdtest_reject_return(gdtest_value, "Node")`,
		},
		{
			name:    "variant",
			source:  "extends RefCounted\n\nfunc pick() -> Variant:\n\treturn null\n",
			check:   []string{"\t\tgdtest_result = gdtest_value"},
			variant: true,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			rendered := renderSource(t, test.source, "")
			for _, line := range test.check {
				assert.Contains(t, rendered, line+"\n")
			}
			if test.variant {
				assert.NotContains(t, rendered, "_gdtest_reject_return")
				assert.Contains(t, rendered, "\tif gdtest_outcome != GDTestDoubleMethod.OUTCOME_NEUTRAL:\n\t\tgdtest_result = gdtest_value\n\treturn gdtest_result\n")
				return
			}
			assert.Contains(t, rendered, test.reject)
		})
	}
}

